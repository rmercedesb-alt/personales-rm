UPDATE ph
SET ph.PrePresupuesto = CASE
        WHEN ph.PrePresupuesto - r.UnidadesProm < 0 THEN 0
        ELSE ph.PrePresupuesto - r.UnidadesProm
    END,
    ph.PreFechaActualizacion = GETDATE()
FROM PresupuestosHistoricos ph
JOIN #Reasignacion r
    ON r.RepCodigoOrigen = ph.RepCodigo
   AND TRY_CAST(ph.PreReferencia AS INT) = r.ProID
WHERE ph.PreAnio = 2026
  AND ph.PreMes = 8
  AND ph.PreTipo = 'UNDDPROD';

PRINT CONCAT('Filas rebajadas a vendedores origen: ', @@ROWCOUNT);

/* ================================================================== *
 * 3) CARGAR/INCREMENTAR presupuesto consolidado al vendedor 185       *
 * ================================================================== */
;WITH Consolidado AS (
    SELECT ProID, SUM(UnidadesProm) AS UnidadesProm
    FROM #Reasignacion
    GROUP BY ProID
)
MERGE PresupuestosHistoricos AS tgt
USING Consolidado AS src
    ON tgt.RepCodigo = '185'
   AND tgt.PreTipo = 'UNDDPROD'
   AND tgt.PreAnio = 2026
   AND tgt.PreMes = 8
   AND TRY_CAST(tgt.PreReferencia AS INT) = src.ProID
WHEN MATCHED THEN
    UPDATE SET tgt.PrePresupuesto = tgt.PrePresupuesto + src.UnidadesProm,
               tgt.PreFechaActualizacion = GETDATE()
WHEN NOT MATCHED THEN
    INSERT (RepCodigo, PreTipo, PreAnio, PreMes, PreReferencia, PrePresupuesto, PreEjecutado, PreFechaActualizacion)
    VALUES ('185', 'UNDDPROD', 2026, 8, CAST(src.ProID AS varchar(20)), src.UnidadesProm, 0, GETDATE());

